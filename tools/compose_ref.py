"""Compose the two RGBA renders from blender/render_ref.py into the two-camera reference frame for the video model.

MOCAP_CREATURE=assets/dragon python tools/compose_ref.py runs/dragon/ref       ref_front.png + ref_side.png -> ref.png
The frame is the layout's: grey studio wall, lighter floor band, front view left, side view right, a dark divider.

It also writes ref_side_studio.png: the SAME side camera, on the SAME studio
backdrop, cropped to the side panel's own columns (layout.W_FRONT:). That file
is the reference a SINGLE-camera clip must be calibrated against.

Why it exists: ref_side.png is the raw alpha render - the wolf on transparent
white, tight-cropped, no floor band. A clip generated by the reference-to-video
route is a grey-studio shot with a floor band, so calibrating it against the
alpha crop compares two different intensity fields. Measured on the R2V shake
clip: ECC against ref_side.png does NOT converge (residual 148 px), while ECC
against this studio panel DOES (cc 0.86, residual 84 px).
"""
import pathlib, sys

import numpy as np
from PIL import Image

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from mocap import layout  # noqa: E402

d = pathlib.Path(sys.argv[1])
f = np.array(Image.open(d / "ref_front.png").convert("RGBA"))
s = np.array(Image.open(d / "ref_side.png").convert("RGBA"))
composed = layout.compose(f, s)
Image.fromarray(composed).save(d / "ref.png")
print("wrote", d / "ref.png", f"{layout.W} x {layout.H}")

# The side panel in the house's own pixel space: the exact columns the
# two-camera read takes as its side view (f[:, layout.W_FRONT:]).
side_panel = composed[:, layout.W_FRONT:]
Image.fromarray(side_panel).save(d / "ref_side_studio.png")
print("wrote", d / "ref_side_studio.png", f"{layout.W_SIDE} x {layout.H}",
      "(the single-camera reference: the side camera on the studio backdrop)")
